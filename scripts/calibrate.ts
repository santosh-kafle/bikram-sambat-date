/**
 * Measures how well the Sūrya Siddhānta projection reproduces the verified
 * calendar, and writes data/ACCURACY.md. Run with `npm run data:calibrate`;
 * add `-- --check` to fail instead of writing when the report is stale.
 *
 * It evaluates the parameters in data/calendar.config.json (`projection`) and,
 * for comparison, every model and time offset in a sweep. The verified years
 * are split in two: BS 2000–2083, which the month rule was worked out from,
 * and BS 1975–1999, which was never looked at while choosing it. A parameter
 * change is only worth making if it also holds on the second set.
 *
 * Fails if any month the projection gets wrong lies outside the uncertainty
 * margin: projected dates are only flagged `uncertain` within that margin, so
 * a confident miss would be a confident wrong answer.
 */
import { writeFile } from 'node:fs/promises';
import {
  applyMonthRule,
  type MonthStart,
  sankrantiJd,
} from './astro/sankranti.js';
import type { SunModel } from './astro/surya-siddhanta.js';
import {
  isoOf,
  loadVerifiedTable,
  monthStarts,
  read,
  root,
} from './lib/verified-table.js';

const FIT_FROM = 2000;
const MODELS: SunModel[] = ['fixed-apogee', 'calendrical-calculations'];
const OFFSETS = Array.from({ length: 31 }, (_, i) => -40 + 2 * i); // −40…+20

interface Trial {
  key: string;
  year: number;
  actual: number;
  projected: MonthStart;
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const verified = await loadVerifiedTable();
  const { projection, minYear, maxYear } = verified.config;
  const actualStarts = monthStarts(verified);

  // Saṅkrāntis per model, computed once.
  const sankrantis = new Map<SunModel, Map<string, number>>();
  for (const model of MODELS) {
    const moments = new Map<string, number>();
    for (const key of actualStarts.keys()) {
      const [year, month] = key.split('-').map(Number) as [number, number];
      moments.set(key, sankrantiJd(year, month, model));
    }
    sankrantis.set(model, moments);
  }

  const run = (model: SunModel, offsetMinutes: number): Trial[] =>
    [...actualStarts].map(([key, actual]) => {
      const month = Number(key.slice(5));
      return {
        key,
        year: Number(key.slice(0, 4)),
        actual,
        projected: applyMonthRule(
          sankrantis.get(model)!.get(key)!,
          month,
          offsetMinutes,
        ),
      };
    });
  const hits = (trials: Trial[]) =>
    trials.filter((t) => t.projected.dayNumber === t.actual).length;
  const split = (trials: Trial[]) => ({
    fit: trials.filter((t) => t.year >= FIT_FROM),
    test: trials.filter((t) => t.year < FIT_FROM),
  });

  // The configured parameters.
  const trials = run(projection.model, projection.offsetMinutes);
  const { fit, test } = split(trials);
  const misses = trials.filter((t) => t.projected.dayNumber !== t.actual);
  const flagged = trials.filter(
    (t) => t.projected.marginMinutes < projection.uncertainMarginMinutes,
  );
  const confidentMisses = misses.filter(
    (t) => t.projected.marginMinutes >= projection.uncertainMarginMinutes,
  );
  const widestMiss = Math.max(
    0,
    ...misses.map((t) => t.projected.marginMinutes),
  );

  // The sweep.
  const sweepRows = MODELS.flatMap((model) =>
    OFFSETS.map((offset) => {
      const s = split(run(model, offset));
      return { model, offset, fit: hits(s.fit), test: hits(s.test) };
    }),
  );
  const best = sweepRows.reduce((a, b) => (b.fit > a.fit ? b : a));

  const percent = (n: number, d: number) => `${((100 * n) / d).toFixed(1)}%`;
  const missRows = misses.map(
    (t) =>
      `| ${t.key} | ${isoOf(t.actual)} | ${isoOf(t.projected.dayNumber)} | ${t.projected.marginMinutes.toFixed(1)} |`,
  );
  const sweepTable = sweepRows
    .filter((r) => r.offset % 4 === 0 || r === best)
    .map(
      (r) =>
        `| ${r.model} | ${r.offset} | ${r.fit}/${fit.length} | ${r.test}/${test.length} |`,
    );

  const report = `# Projection accuracy

Generated by \`npm run data:calibrate\`. Do not edit by hand. The method is
described in [docs/projection.md](../docs/projection.md).

The Sūrya Siddhānta projection is run over every verified month, BS ${minYear}–${maxYear},
and its month starts are compared with the published ones.

## Parameters in use

From \`projection\` in \`data/calendar.config.json\`:

- **Model:** ${projection.model}
- **Time offset:** ${projection.offsetMinutes} minutes
- **Uncertainty margin:** ${projection.uncertainMarginMinutes} minutes

## Results

| Months | Projected correctly |
| --- | --- |
| BS ${FIT_FROM}–${maxYear} (the rule was worked out from these) | ${hits(fit)}/${fit.length} (${percent(hits(fit), fit.length)}) |
| BS ${minYear}–${FIT_FROM - 1} (never used to choose the rule) | ${hits(test)}/${test.length} (${percent(hits(test), test.length)}) |
| **All** | **${hits(trials)}/${trials.length} (${percent(hits(trials), trials.length)})** |

- **Flagged uncertain:** ${flagged.length} of ${trials.length} months (${percent(flagged.length, trials.length)}) have a saṅkrānti within ${projection.uncertainMarginMinutes} minutes of a boundary.
- **Misses inside the margin:** ${misses.length - confidentMisses.length} of ${misses.length}. The widest miss was ${widestMiss.toFixed(1)} minutes from a boundary.
- **Unflagged months correct:** ${trials.length - flagged.length - confidentMisses.length} of ${trials.length - flagged.length}.

## Months the projection gets wrong

| Month | Published start | Projected start | Minutes from boundary |
| --- | --- | --- | --- |
${missRows.join('\n')}

## Sweep

Correct month starts for each model and offset (every 4 minutes, plus the
best fit). Best on BS ${FIT_FROM}–${maxYear}: ${best.model}, ${best.offset} minutes.

| Model | Offset (min) | BS ${FIT_FROM}–${maxYear} | BS ${minYear}–${FIT_FROM - 1} |
| --- | --- | --- | --- |
${sweepTable.join('\n')}
`;

  if (confidentMisses.length > 0) {
    throw new Error(
      `Projection misses outside the ${projection.uncertainMarginMinutes}-minute margin: ` +
        confidentMisses
          .map((t) => `${t.key} (${t.projected.marginMinutes.toFixed(1)} min)`)
          .join(', '),
    );
  }

  const path = 'data/ACCURACY.md';
  if (check) {
    if ((await read(path).catch(() => '')) !== report) {
      throw new Error(`Out of date (run npm run data:calibrate): ${path}`);
    }
    console.log('Projection accuracy report is up to date.');
    return;
  }
  await writeFile(new URL(path, root), report);
  console.log(
    `${hits(trials)}/${trials.length} month starts correct; ` +
      `${flagged.length} flagged uncertain, including all ${misses.length} misses. ` +
      `Best sweep fit: ${best.model} ${best.offset} min (${best.fit}/${fit.length}, out of sample ${best.test}/${test.length}).`,
  );
}

await main();
